"""
Lightweight FastAPI application for the Hotel Receptionist Agent API.
Accepts JSON chat requests and queries Gemini 3.8 Flash directly.
"""

import os
from typing import Optional
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from agent import receptionist_agent

app = FastAPI(
    title="Hotel Voice Receptionist API",
    description="Lightweight Hotel Voice Receptionist Agent powered by Gemini 3.8 Flash",
    version="1.0.0",
)

# Enable CORS for testing
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class ChatRequest(BaseModel):
    message: str = Field(..., description="Message from the hotel guest")
    session_id: Optional[str] = Field("default", description="Conversation session ID for multi-turn history")


class ResetRequest(BaseModel):
    session_id: Optional[str] = Field("default", description="Session ID to clear")


@app.get("/")
def get_info():
    """Returns API information and an example JSON payload for testing."""
    has_key = bool(
        os.getenv("GEMINI_API_KEY", "").strip()
        and os.getenv("GEMINI_API_KEY") != "your_gemini_api_key_here"
    )
    return {
        "status": "online",
        "service": "Grand Azure Hotel Voice Receptionist API",
        "model": receptionist_agent.model,
        "has_api_key": has_key,
        "endpoint": "POST /chat",
        "sample_request_json": {
            "message": "Do you have any rooms available tonight?",
            "session_id": "test-session-1"
        },
        "try_questions": [
            "Do you have any rooms available tonight? What are the prices?",
            "What is the Wi-Fi network and password?",
            "Can you look up the reservation for John Doe?",
            "Can I get extra towels sent to room 402?",
            "What time is breakfast served?",
            "Please book a Deluxe Queen Suite for 2 nights for Alex Smith"
        ]
    }


@app.post("/chat")
@app.post("/api/chat")
def chat_endpoint(req: ChatRequest):
    """
    Receives guest message and returns the response generated by Gemini 3.8 Flash.
    """
    try:
        session_id = req.session_id or "default"
        res = receptionist_agent.respond(message=req.message, session_id=session_id)
        return res
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/reset")
def reset_endpoint(req: ResetRequest):
    """Clears conversation memory for a given session."""
    session_id = req.session_id or "default"
    receptionist_agent.clear_session(session_id)
    return {"status": "success", "message": f"Session '{session_id}' cleared."}


if __name__ == "__main__":
    import uvicorn
    port = int(os.getenv("PORT", 8000))
    print(f"Starting Hotel Voice Receptionist API on http://localhost:{port}")
    uvicorn.run("main:app", host="0.0.0.0", port=port, reload=True)
